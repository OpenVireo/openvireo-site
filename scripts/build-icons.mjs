// Writes assets/scss/_icons.scss: one `.ic-<name>` rule for every icon class the site uses.
//
// Icons are Fluent UI System Icons (@fluentui/svg-icons, MIT), 20px regular, drawn as a CSS mask so they
// take the text colour and size like a font icon would. Brand logos Fluent lacks live in assets/icons/brands.
// Usage: <i class="ic ic-arrow-download" aria-hidden="true"></i>, the name being the Fluent file name with
// dashes (arrow_download_20_regular.svg → ic-arrow-download); stylesheets can use the Sass variable
// $ic-<name> as a mask image. Run `npm run icons` after adding one.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fluentDir = path.join(root, 'node_modules/@fluentui/svg-icons/icons');
const brandDir = path.join(root, 'assets/icons/brands');
const out = path.join(root, 'assets/scss/_icons.scss');

const scan = ['layouts', 'content', 'assets/js', 'scripts', 'archetypes', 'data', 'hugo.toml'];
const names = new Set();
const walk = (p) => {
    if (fs.statSync(p).isDirectory()) return fs.readdirSync(p).forEach((f) => walk(path.join(p, f)));
    if (!/\.(html|md|js|mjs|toml|ya?ml|json)$/.test(p) || p === fileURLToPath(import.meta.url)) return;
    for (const [, n] of fs.readFileSync(p, 'utf8').matchAll(/(?<![\w-])ic-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(n);
};
scan.forEach((p) => walk(path.join(root, p)));

const dataUri = (svg) => {
    const min = svg.replace(/<\?xml[^>]*>/, '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
    return `url("data:image/svg+xml,${min.replace(/"/g, "'").replace(/[<>#%{}]/g, encodeURIComponent)}")`;
};

const missing = [];
const rules = [...names].sort().map((n) => {
    const brand = path.join(brandDir, `${n}.svg`);
    const fluent = path.join(fluentDir, `${n.replace(/-/g, '_')}_20_regular.svg`);
    const file = [brand, fluent].find((f) => fs.existsSync(f));
    if (!file) return missing.push(n), '';
    return `$ic-${n}: ${dataUri(fs.readFileSync(file, 'utf8'))};\n.ic-${n} { --ic: #{$ic-${n}}; }\n`;
});
if (missing.length) {
    console.error(`No Fluent or brand icon for: ${missing.map((n) => `ic-${n}`).join(', ')}`);
    process.exit(1);
}

fs.writeFileSync(out, `// Generated by scripts/build-icons.mjs (npm run icons); do not edit by hand.
// Fluent UI System Icons, MIT, https://github.com/microsoft/fluentui-system-icons
// Brand logos: assets/icons/brands (Simple Icons, CC0 1.0)

.ic {
    display: inline-block;
    width: 1em;
    height: 1em;
    flex: none;
    vertical-align: -0.125em;
    background-color: currentColor;
    -webkit-mask: var(--ic) center / contain no-repeat;
    mask: var(--ic) center / contain no-repeat;
    font-style: normal;
}

${rules.join('')}`);
console.log(`Wrote ${names.size} icons to ${path.relative(root, out)}`);
