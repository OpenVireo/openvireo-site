// Generates assets/scss/_fluent-theme.scss: Fluent 2 design tokens (light + dark) built
// from a KeePassXC-green brand ramp. Re-run after changing BRAND or upgrading @fluentui/tokens:
//
//     node scripts/generate-theme.mjs
//
// The tokens are emitted as static CSS custom properties so the theme applies before any
// JavaScript runs (and with JavaScript disabled).

import { writeFileSync } from 'node:fs';
import { createDarkTheme, createLightTheme } from '@fluentui/tokens';

const BRAND = '#45862b';

// Fluent's default web brand ramp; we reuse its lightness curve so our ramp behaves like
// the stock one (same contrast characteristics for every token that maps onto it).
const brandWeb = {
    10: '#061724', 20: '#082338', 30: '#0a2e4a', 40: '#0c3b5e', 50: '#0e4775', 60: '#0f548c',
    70: '#115ea3', 80: '#0f6cbd', 90: '#2886de', 100: '#479ef5', 110: '#62abf5', 120: '#77b7f7',
    130: '#96c6fa', 140: '#b4d6fa', 150: '#cfe4fa', 160: '#ebf3fc',
};

// --- sRGB <-> OKLCH -------------------------------------------------------------------------

const toLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const fromLinear = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);

function hexToRgb(hex) {
    const n = parseInt(hex.slice(1), 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => v / 255);
}

function rgbToHex(rgb) {
    return '#' + rgb.map((v) => Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, '0')).join('');
}

function rgbToOklch(rgb) {
    const [r, g, b] = rgb.map(toLinear);
    const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
    const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
    const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
    const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
    const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
    const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
    return [L, Math.hypot(A, B), Math.atan2(B, A)];
}

function oklchToRgb([L, C, h]) {
    const A = C * Math.cos(h);
    const B = C * Math.sin(h);
    const l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
    const m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
    const s = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
    return [
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
    ].map(fromLinear);
}

const inGamut = (rgb) => rgb.every((v) => v >= -1e-4 && v <= 1 + 1e-4);

function luminance(hex) {
    const [r, g, b] = hexToRgb(hex).map(toLinear);
    return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
    const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
    return (hi + 0.05) / (lo + 0.05);
}

// --- Brand ramp -----------------------------------------------------------------------------

const [, brandChroma, brandHue] = rgbToOklch(hexToRgb(BRAND));
const brand = {};
for (const [step, ref] of Object.entries(brandWeb)) {
    const [L, refChroma] = rgbToOklch(hexToRgb(ref));
    // Follow the reference ramp's chroma profile, scaled to our brand's saturation,
    // then pull chroma in until the color fits the sRGB gamut.
    let C = refChroma * (brandChroma / rgbToOklch(hexToRgb(brandWeb[80]))[1]);
    let rgb = oklchToRgb([L, C, brandHue]);
    while (!inGamut(rgb) && C > 0) {
        C -= 0.002;
        rgb = oklchToRgb([L, C, brandHue]);
    }
    brand[step] = rgbToHex(rgb);
}

// --- Themes ---------------------------------------------------------------------------------

const fontFamilyBase = `'Nunito Sans', 'Segoe UI', 'Segoe UI Web (West European)', -apple-system, BlinkMacSystemFont, Roboto, 'Helvetica Neue', sans-serif`;
const light = { ...createLightTheme(brand), fontFamilyBase };
const dark = { ...createDarkTheme(brand), fontFamilyBase };

// The dark theme's brand foreground tokens are tuned for blue; nudge them one step lighter
// so green links stay comfortably readable on the dark neutral backgrounds.
dark.colorBrandForeground1 = brand[110];
dark.colorBrandForegroundLink = brand[110];
dark.colorBrandForegroundLinkHover = brand[120];

const decls = (theme, keys = Object.keys(theme)) => keys.map((k) => `    --${k}: ${theme[k]};`).join('\n');
const changedInDark = Object.keys(dark).filter((k) => dark[k] !== light[k]);

const css = `// GENERATED by scripts/generate-theme.mjs -- do not edit by hand.
// Fluent 2 design tokens with the KeePassXC brand ramp (base ${BRAND}).
//
// Brand ramp: ${Object.entries(brand).map(([k, v]) => `${k}=${v}`).join(' ')}
// Contrast on white: brand80 ${contrast(brand[80], '#ffffff').toFixed(2)}:1, brand70 ${contrast(brand[70], '#ffffff').toFixed(2)}:1

$brand-ramp: (
${Object.entries(brand).map(([k, v]) => `    ${k}: ${v},`).join('\n')}
);

:root {
    color-scheme: light dark;
${decls(light)}
}

@mixin fluent-dark-tokens {
${decls(dark, changedInDark)}
}

@media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
        @include fluent-dark-tokens;
    }
}

:root[data-theme="dark"] {
    @include fluent-dark-tokens;
}
`;

writeFileSync(new URL('../assets/scss/_fluent-theme.scss', import.meta.url), css);
console.log('Brand ramp:', brand);
console.log(`brand80 on white: ${contrast(brand[80], '#ffffff').toFixed(2)}:1`);
console.log(`white on brand80: ${contrast('#ffffff', brand[80]).toFixed(2)}:1`);
console.log(`dark link (brand110) on #292929: ${contrast(brand[110], '#292929').toFixed(2)}:1`);
console.log(`Wrote ${Object.keys(light).length} light tokens, ${changedInDark.length} dark overrides.`);
